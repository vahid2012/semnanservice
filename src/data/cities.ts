export function getIndexedCities(): City[] {
  return cities.filter((c) => c.indexed);
}

export function getCity(slug: string): City | undefined {
  return cities.find((c) => c.slug === slug);
}

export function getCityByEnSlug(slugEn: string): City | undefined {
  return cities.find((c) => c.slugEn === slugEn);
}

export function getNeighbors(slug: string): City[] {
  const neighborSlugs = neighborsMap[slug] || [];
  return neighborSlugs
    .map((s) => getCity(s))
    .filter((c): c is City => c !== undefined);
}
